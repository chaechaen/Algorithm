-- 임시 테이블 만들기 (RECURSIVE 재귀로 반복문 구현)
WITH RECURSIVE HOUR_TABLE AS (
    SELECT 0 AS HOUR -- 초기값 HOUR=0
    
    UNION ALL
    
    SELECT HOUR + 1
    FROM HOUR_TABLE
    WHERE HOUR < 23
)

SELECT H.HOUR AS HOUR, COUNT(A.ANIMAL_ID) AS COUNT
FROM HOUR_TABLE H
LEFT JOIN ANIMAL_OUTS A ON H.HOUR = HOUR(TIME(A.DATETIME))
GROUP BY H.HOUR
ORDER BY H.HOUR ASC